        private static void Add(ModLanguage lang, Dictionary<string, string> table)
        {
            if (s_extra == null) return;
            if (!s_extra.TryGetValue(lang, out var dest) || dest == null)
            {
                dest = new Dictionary<string, string>();
                s_extra[lang] = dest;
            }
            foreach (var kv in table)
                dest[kv.Key] = kv.Value;
        }
